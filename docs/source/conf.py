# Add source directory so Sphinx can import xpm_torch without installing
# the full project (which would pull in torch, lightning, etc.)
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))


def _get_version() -> str:
    """Documented version, without importing xpm_torch (needs numpy)

    version.py is generated by hatch-vcs when the project is installed, which
    is not the case on RTD: fall back to the latest git tag.
    """
    version_file = ROOT / "src" / "xpm_torch" / "version.py"
    if version_file.exists():
        return runpy.run_path(str(version_file))["__version__"]
    try:
        tag = subprocess.check_output(
            ["git", "describe", "--tags", "--abbrev=0"], cwd=ROOT, text=True
        )
        return tag.strip().removeprefix("v")
    except (OSError, subprocess.CalledProcessError):
        return "0.0.0"


